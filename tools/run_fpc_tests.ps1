param(
  # Which FreePascal builds and runs the test suite (tools/fpc_toolchains.ps1):
  #   Wsl    - FreePascal inside WSL (default compiler ~/fpc-3.2.4/bin/fpc of
  #            the WSL user, override with -FpcPath)
  #   Native - the FreePascal on PATH of this machine (or -FpcPath): Windows,
  #            or Linux/macOS when this script runs under pwsh there (CI)
  #   Mac    - the shared Mac toolchain behind the ssh alias -MacHost, built
  #            with ~/remote-toolchains/macos-fpc/bin/fpc.sh
  [ValidateSet("Wsl", "Native", "Mac")]
  [string]$Toolchain = "Wsl",
  [string]$FpcPath = "",
  [string]$MacHost = "macos-tests",
  # PARENT directory of the scratch space. The script creates and removes only
  # its own uniquely named subdirectory below it and never deletes the
  # directory it was given.
  [string]$WorkDir = "",
  # Copy the JUnit XML report of the run to this file.
  [string]$JUnit = "",
  # Passed to the runner as --filter (<Fixture>[.<Test>], comma separated).
  [string]$Filter = "",
  # Build only, do not run.
  [switch]$BuildOnly,
  [switch]$RequireFpc,
  [switch]$KeepWorkDir,
  [switch]$Quiet
)

<#
  Builds tests/LibPhoneNumberTests.dpr - the whole test suite, the same source
  the Delphi build runs - with FreePascal and runs it.

  The build uses the options of the FreePascal runtime gate: Delphi mode,
  ansistrings, range and overflow checking, line info. A compiler error or
  WARNING fails the build (hints and notes do not), like the two other
  FreePascal gates. The runner's exit code decides the result: 0 only when
  every test passed.

  The test program finds tests/data by searching upwards from its own
  directory and from the current directory; every mode therefore starts it
  from the tests directory (Wsl, Native) or from a staged copy of it (Mac).

  Like the other FreePascal gates the script is a no-op with a warning when
  the selected toolchain is not reachable; -RequireFpc turns that into a
  failure.

  Mac mode copies src/, tests/ (sources, framework, data) and a build script
  into a fresh run directory
  ~/remote-toolchains/macos-fpc/runs/libphonenumber-tests-<utc>-<id>/ on
  -MacHost, builds and runs there and copies the logs and the JUnit report
  back. Remote runs are kept for review, as the toolchain README asks.
#>

$ErrorActionPreference = "Stop"

. (Join-Path $PSScriptRoot "fpc_toolchains.ps1")

$repoRoot = Split-Path -Parent $PSScriptRoot
$sourceDir = Join-Path $repoRoot "src"
$testsDir = Join-Path $repoRoot "tests"
$programName = "LibPhoneNumberTests"
$programFile = Join-Path $testsDir ($programName + ".dpr")

# Same options as tools/run_fpc_runtime_check.ps1.
$fpcOptions = @("-B", "-Mdelphi", "-Sh", "-Cr", "-Co", "-gl")

function Write-Info {
  param([string]$Message)
  if (-not $Quiet) {
    Write-Host $Message
  }
}

if ([string]::IsNullOrWhiteSpace($WorkDir)) {
  $WorkDir = [System.IO.Path]::GetTempPath()
}
# Absolute from here on: the script changes its location (Push-Location) and
# hands paths to other processes, so a relative -WorkDir would resolve
# against a different directory later.
$WorkDir = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($WorkDir)
if (-not [string]::IsNullOrWhiteSpace($JUnit)) {
  $JUnit = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($JUnit)
}
$scratchDir = Join-Path $WorkDir ("libphonenumber-fpctests-{0}" -f $PID)

if (-not (Test-Path -LiteralPath $programFile)) {
  throw "Test program not found: $programFile"
}

$fpc = Resolve-FpcToolchain -Toolchain $Toolchain -FpcPath $FpcPath -MacHost $MacHost
if ([string]::IsNullOrWhiteSpace($fpc)) {
  Skip-OrFail "FreePascal toolchain '$Toolchain' not reachable; skipping the FreePascal test suite." $RequireFpc
  return
}

function Get-RunnerArguments {
  # The runner arguments, each already a single word for a POSIX shell when
  # -ForShell is given.
  param([string]$JUnitPath, [switch]$ForShell)
  $arguments = @()
  if (-not [string]::IsNullOrWhiteSpace($JUnitPath)) {
    $arguments += "--junit"
    $arguments += $JUnitPath
  }
  if (-not [string]::IsNullOrWhiteSpace($Filter)) {
    $arguments += "--filter"
    $arguments += $Filter
  }
  if ($ForShell) {
    return @($arguments | ForEach-Object { ConvertTo-RemoteShellWord $_ })
  }
  return $arguments
}

function Write-UnixScript {
  # The build (and run) step of the Wsl and the Mac mode, run as
  # "sh <script> <args>" so no $-containing one liner has to survive
  # PowerShell, wsl.exe or ssh quoting. The runner arguments come last and are
  # passed through unchanged.
  param([string]$Path)
  $options = $fpcOptions -join " "
  $lines = @(
    '#!/bin/sh',
    '# Generated by tools/run_fpc_tests.ps1.',
    '# Arguments: <fpc> <source dir> <tests dir> <output dir> <build only: 0|1> [runner arguments...]',
    'fpc="$1"; src="$2"; tests="$3"; out="$4"; buildonly="$5"; shift 5',
    'mkdir -p "$out/units" || exit 2',
    '{ "$fpc" -iV; "$fpc" -iTP; "$fpc" -iTO; } > "$out/fpc-info.txt" 2>&1',
    ('"$fpc" ' + $options + ' -FU"$out/units" -FE"$out" -Fu"$src" -Fu"$tests/framework" "$tests/' + $programName + '.dpr" > "$out/build.log" 2>&1'),
    'status=$?',
    'if [ $status -ne 0 ]; then cat "$out/build.log"; echo "FPC build failed (exit $status)"; exit 3; fi',
    'if [ "$buildonly" = "1" ]; then exit 0; fi',
    'cd "$tests" || exit 2',
    ('"$out/' + $programName + '" "$@" > "$out/run.log" 2>&1'),
    'status=$?',
    'cat "$out/run.log"',
    'if [ $status -ne 0 ]; then exit 10; fi',
    'exit 0'
  )
  Write-LfAsciiFile -Path $Path -Lines $lines
}

function Assert-CleanBuild {
  param([string[]]$BuildOutput)
  $problems = Get-FpcProblems $BuildOutput
  if ($problems.Count -gt 0) {
    $BuildOutput | ForEach-Object { Write-Host "    $_" }
    throw "The FreePascal build of the test program reported $($problems.Count) error/warning line(s)."
  }
}

Write-Info "FreePascal test suite ($Toolchain)"

if (Test-Path -LiteralPath $scratchDir) {
  Remove-Item -LiteralPath $scratchDir -Recurse -Force
}
[void](New-Item -ItemType Directory -Path $scratchDir -Force)
$outDir = Join-Path $scratchDir "out"
[void](New-Item -ItemType Directory -Path (Join-Path $outDir "units") -Force)
$junitFile = Join-Path $outDir "junit.xml"

$succeeded = $false
$runExitCode = 0
$runOutput = @()
$watch = [System.Diagnostics.Stopwatch]::StartNew()
try {
  switch ($Toolchain) {
    "Native" {
      $fpcVersion = Get-NativeFpcDescription $fpc
      $build = Invoke-Native $fpc ($fpcOptions + @(("-FU" + (Join-Path $outDir "units")), "-FE$outDir",
        "-Fu$sourceDir", ("-Fu" + (Join-Path $testsDir "framework")), $programFile))
      if ($build.ExitCode -ne 0) {
        $build.Output | ForEach-Object { Write-Host "    $_" }
        throw "The FreePascal build of the test program failed (exit code $($build.ExitCode))."
      }
      Assert-CleanBuild $build.Output
      if (-not $BuildOnly) {
        $exe = Join-Path $outDir $programName
        if (Test-Path -LiteralPath ($exe + ".exe")) {
          $exe = $exe + ".exe"
        }
        Push-Location $testsDir
        try {
          $run = Invoke-Native $exe (Get-RunnerArguments -JUnitPath $junitFile)
        } finally {
          Pop-Location
        }
        $runOutput = $run.Output
        $runExitCode = $run.ExitCode
      }
    }
    "Wsl" {
      $unixScript = Join-Path $scratchDir "build_and_run.sh"
      Write-UnixScript -Path $unixScript
      $flag = if ($BuildOnly) { "1" } else { "0" }
      $result = Invoke-Native "wsl.exe" (@("-e", "sh", (ConvertTo-WslPath $unixScript), $fpc,
        (ConvertTo-WslPath $sourceDir), (ConvertTo-WslPath $testsDir),
        (ConvertTo-WslPath $outDir), $flag) + (Get-RunnerArguments -JUnitPath (ConvertTo-WslPath $junitFile)))
      if ($result.ExitCode -ne 0 -and $result.ExitCode -ne 10) {
        $result.Output | ForEach-Object { Write-Host "    $_" }
        throw "The WSL FreePascal build or run failed (exit code $($result.ExitCode))."
      }
      Assert-CleanBuild @(Get-Content -LiteralPath (Join-Path $outDir "build.log"))
      $info = @(Get-Content -LiteralPath (Join-Path $outDir "fpc-info.txt"))
      $fpcVersion = "{0} ({1}-{2})" -f $info[0], $info[1], $info[2]
      $runOutput = $result.Output
      $runExitCode = if ($result.ExitCode -eq 10) { 1 } else { 0 }
    }
    "Mac" {
      $unixScript = Join-Path $scratchDir "build_and_run.sh"
      Write-UnixScript -Path $unixScript

      # Exactly what the remote build and run need: the units of src/, the
      # test program with its units and framework, the data files.
      $stage = Join-Path $scratchDir "mac-stage"
      foreach ($dir in @("src", "tests", "tests/framework", "tests/data")) {
        [void](New-Item -ItemType Directory -Path (Join-Path $stage $dir) -Force)
      }
      Copy-Item -Path (Join-Path $sourceDir "*.pas") -Destination (Join-Path $stage "src")
      Copy-Item -Path (Join-Path $testsDir "*.pas") -Destination (Join-Path $stage "tests")
      Copy-Item -LiteralPath $programFile -Destination (Join-Path $stage "tests")
      Copy-Item -Path (Join-Path $testsDir "framework\*.pas") -Destination (Join-Path $stage "tests/framework")
      Copy-Item -Path (Join-Path $testsDir "data\*.json") -Destination (Join-Path $stage "tests/data")
      Copy-Item -LiteralPath $unixScript -Destination $stage

      $remoteRun = New-MacRunDirectory -MacHost $MacHost -Prefix "libphonenumber-tests"
      Send-MacStage -MacHost $MacHost -RemoteRun $remoteRun -StageDir $stage -ScratchDir $scratchDir
      $flag = if ($BuildOnly) { "1" } else { "0" }
      $remoteCommand = ("cd $remoteRun && sh build_and_run.sh $(ConvertTo-RemoteShellWord $fpc) " +
        "`"`$PWD/src`" `"`$PWD/tests`" `"`$PWD/out`" $flag " +
        ((Get-RunnerArguments -JUnitPath "junit.xml" -ForShell) -join " "))
      $result = Invoke-Native "ssh" @($MacHost, $remoteCommand)
      if ($result.ExitCode -ne 0 -and $result.ExitCode -ne 10) {
        $result.Output | ForEach-Object { Write-Host "    $_" }
        throw "The Mac FreePascal build or run failed (exit code $($result.ExitCode)); run kept at ~/$remoteRun."
      }
      foreach ($name in @("build.log", "fpc-info.txt")) {
        [void](Receive-MacFile -MacHost $MacHost -RemoteRun $remoteRun -RelativePath "out/$name" `
          -Destination (Join-Path $outDir $name))
      }
      if (-not $BuildOnly) {
        # The runner writes the report relative to its working directory, the
        # staged tests directory.
        [void](Receive-MacFile -MacHost $MacHost -RemoteRun $remoteRun -RelativePath "tests/junit.xml" `
          -Destination $junitFile -Optional)
      }
      Assert-CleanBuild @(Get-Content -LiteralPath (Join-Path $outDir "build.log"))
      $info = @(Get-Content -LiteralPath (Join-Path $outDir "fpc-info.txt"))
      $fpcVersion = "{0} ({1}-{2}), run ~/{3}" -f $info[0], $info[1], $info[2], $remoteRun
      $runOutput = $result.Output
      $runExitCode = if ($result.ExitCode -eq 10) { 1 } else { 0 }
    }
  }

  Write-Info ("  FreePascal : {0} via {1}" -f $fpcVersion, $fpc)
  if ($BuildOnly) {
    Write-Info ("  build only (-BuildOnly): the test program compiled, tests not run ({0:N1} s)." -f
      $watch.Elapsed.TotalSeconds)
    $succeeded = $true
    return
  }

  foreach ($line in $runOutput) {
    Write-Host "  $line"
  }
  Write-Info ("  build + run {0:N1} s" -f $watch.Elapsed.TotalSeconds)

  if (-not [string]::IsNullOrWhiteSpace($JUnit)) {
    if (Test-Path -LiteralPath $junitFile) {
      $target = $JUnit
      $targetDir = Split-Path -Parent $target
      if (-not (Test-Path -LiteralPath $targetDir)) {
        [void](New-Item -ItemType Directory -Path $targetDir -Force)
      }
      Copy-Item -LiteralPath $junitFile -Destination $target -Force
      Write-Info "  JUnit report: $target"
    } else {
      Write-Warning "The test run wrote no JUnit report."
    }
  }

  $summary = @($runOutput | Where-Object { $_ -match '^Tests: \d+' }) | Select-Object -Last 1
  if ($runExitCode -ne 0 -or [string]::IsNullOrWhiteSpace($summary)) {
    throw "FreePascal test run reported failures (exit code $runExitCode): $summary"
  }
  $succeeded = $true
  Write-Info "FreePascal test suite passed."
} finally {
  if ($KeepWorkDir) {
    Write-Info ("  work directory kept: {0}" -f $scratchDir)
  } elseif ($succeeded -and (Test-Path -LiteralPath $scratchDir)) {
    for ($attempt = 1; $attempt -le 5 -and (Test-Path -LiteralPath $scratchDir); $attempt++) {
      Remove-Item -LiteralPath $scratchDir -Recurse -Force -ErrorAction SilentlyContinue
      if (Test-Path -LiteralPath $scratchDir) {
        [System.Threading.Thread]::Sleep(200)
      }
    }
  } elseif (-not $succeeded -and (Test-Path -LiteralPath $scratchDir)) {
    Write-Info ("  work directory kept for inspection: {0}" -f $scratchDir)
  }
}
